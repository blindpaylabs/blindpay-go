package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// The typed error codes are generated from the spec's "Errors" tag, whose
// description holds the error table:
//
//	| `QUOTES_EXPIRED` | 400 | actionable | This quote has expired. ... |
//
// Two files are written: the lookup table in internal/request (so
// APIError.RetryClass can use it) and the exported ErrorCode* constants in
// the root package. -check reports a stale table as a pending change, so a
// new code in the spec fails CI; -apply regenerates both files.
const (
	errorCodesRootFile     = "errorcodes_gen.go"
	errorCodesInternalFile = "internal/request/errorcodes_gen.go"
	errorCodesHeader       = "// Code generated by cmd/apisync from the spec's Errors tag; DO NOT EDIT.\n\n"
)

var (
	errorCodeRowRE      = regexp.MustCompile("^\\| `([A-Z0-9_]+)` \\| ([0-9]{3}) \\| ([a-z]+) \\| (.*?) \\|$")
	errorCodeExistingRE = regexp.MustCompile(`(?m)^\t"([A-Z0-9_]+)":\s+\{`)
	retryClassConst     = map[string]string{
		"retryable":  "RetryClassRetryable",
		"terminal":   "RetryClassTerminal",
		"actionable": "RetryClassActionable",
	}
)

type errorCodeRow struct {
	Code        string
	Status      string
	Retry       string
	Description string
}

// parseErrorCodeTable returns the rows of the Errors tag's table. found is
// false when the spec has no Errors tag at all; a tag whose table has no
// rows, a row with an unknown retry class, a duplicate code or two codes
// mapping to one Go identifier is an error.
func parseErrorCodeTable(raw map[string]any) (rows []errorCodeRow, found bool, err error) {
	tags, _ := raw["tags"].([]any)
	var desc string
	for _, t := range tags {
		tag, _ := t.(map[string]any)
		if name, _ := tag["name"].(string); name == "Errors" {
			desc, _ = tag["description"].(string)
			found = true
			break
		}
	}
	if !found {
		return nil, false, nil
	}

	seen := map[string]bool{}
	idents := map[string]string{}
	for _, line := range strings.Split(desc, "\n") {
		m := errorCodeRowRE.FindStringSubmatch(strings.TrimSpace(line))
		if m == nil {
			continue
		}
		row := errorCodeRow{Code: m[1], Status: m[2], Retry: m[3], Description: strings.TrimSpace(m[4])}
		if _, ok := retryClassConst[row.Retry]; !ok {
			return nil, true, fmt.Errorf("error code %s: unknown retry class %q", row.Code, row.Retry)
		}
		if seen[row.Code] {
			return nil, true, fmt.Errorf("error code %s is listed twice", row.Code)
		}
		seen[row.Code] = true
		ident := errorCodeIdent(row.Code)
		if other, ok := idents[ident]; ok {
			return nil, true, fmt.Errorf("error codes %s and %s both map to %s", other, row.Code, ident)
		}
		idents[ident] = row.Code
		rows = append(rows, row)
	}
	if len(rows) == 0 {
		return nil, true, fmt.Errorf("the spec's Errors tag has no error-code table rows")
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].Code < rows[j].Code })
	return rows, true, nil
}

func errorCodeIdent(code string) string {
	return "ErrorCode" + goIdent(strings.ToLower(code))
}

// renderErrorCodes returns the gofmt'd contents of both generated files.
func renderErrorCodes(rows []errorCodeRow) (map[string][]byte, error) {
	var internal bytes.Buffer
	internal.WriteString(errorCodesHeader)
	internal.WriteString("package request\n\n")
	internal.WriteString("// errorCodes is the error table from the API spec's Errors tag.\n")
	internal.WriteString("var errorCodes = map[ErrorCode]ErrorCodeInfo{\n")
	for _, r := range rows {
		fmt.Fprintf(&internal, "\t%q: {Status: %s, Retry: %s},\n", r.Code, r.Status, retryClassConst[r.Retry])
	}
	internal.WriteString("}\n")

	var root bytes.Buffer
	root.WriteString(errorCodesHeader)
	root.WriteString("package blindpay\n\n")
	root.WriteString("// Error codes from the API's error table (the spec's Errors tag). Each\n")
	root.WriteString("// comment gives the typical HTTP status, the retry class and the API's\n")
	root.WriteString("// description. Compare with blindpay.ErrorCode(apiErr.Code).\n")
	root.WriteString("const (\n")
	for _, r := range rows {
		fmt.Fprintf(&root, "\t// %s (%s, %s): %s\n", errorCodeIdent(r.Code), r.Status, r.Retry, commentSafe(r.Description))
		fmt.Fprintf(&root, "\t%s ErrorCode = %q\n", errorCodeIdent(r.Code), r.Code)
	}
	root.WriteString(")\n")

	out := map[string][]byte{}
	for file, buf := range map[string]*bytes.Buffer{errorCodesInternalFile: &internal, errorCodesRootFile: &root} {
		src, err := format.Source(buf.Bytes())
		if err != nil {
			return nil, fmt.Errorf("formatting %s: %w", file, err)
		}
		out[file] = src
	}
	return out, nil
}

func commentSafe(s string) string {
	return strings.Join(strings.Fields(s), " ")
}

// planErrorCodes reconciles the generated error-code files with the target
// spec. A code that disappears from the spec is NEEDS_HUMAN: its exported
// constant is public API and the module stays v1.
func planErrorCodes(repoRoot string, spec *specDoc) ([]action, []string) {
	internalPath := filepath.Join(repoRoot, errorCodesInternalFile)
	existing, readErr := os.ReadFile(internalPath) //#nosec G304 -- fixed repo-relative path
	rows, found, err := parseErrorCodeTable(spec.raw)
	if !found {
		if readErr == nil {
			return nil, []string{"NEEDS_HUMAN: the target spec has no Errors tag, but " + errorCodesInternalFile + " exists; the error-code table cannot be checked"}
		}
		return nil, nil // a spec and repo without typed error codes (e.g. a test fixture)
	}
	if err != nil {
		return nil, []string{"NEEDS_HUMAN: " + err.Error()}
	}

	inSpec := map[string]bool{}
	for _, r := range rows {
		inSpec[r.Code] = true
	}
	var needsHuman, added []string
	known := map[string]bool{}
	for _, m := range errorCodeExistingRE.FindAllStringSubmatch(string(existing), -1) {
		known[m[1]] = true
		if !inSpec[m[1]] {
			needsHuman = append(needsHuman, fmt.Sprintf("NEEDS_HUMAN: error code %s is in %s but no longer in the spec's Errors table; its exported constant must stay (v1), so keep it by hand or confirm with the API owner", m[1], errorCodesRootFile))
		}
	}
	for _, r := range rows {
		if !known[r.Code] {
			added = append(added, r.Code)
		}
	}
	if len(needsHuman) > 0 {
		return nil, needsHuman
	}

	files, err := renderErrorCodes(rows)
	if err != nil {
		return nil, []string{"NEEDS_HUMAN: " + err.Error()}
	}
	stale := false
	for file, want := range files {
		got, err := os.ReadFile(filepath.Join(repoRoot, file)) //#nosec G304 -- fixed repo-relative path
		if err != nil || !bytes.Equal(got, want) {
			stale = true
		}
	}
	if !stale {
		return nil, nil
	}

	desc := fmt.Sprintf("error codes: regenerate %s and %s from the spec's Errors table", errorCodesRootFile, errorCodesInternalFile)
	bump := "patch" // metadata or description change only
	if len(added) > 0 {
		desc += fmt.Sprintf(" (%d added: %s)", len(added), strings.Join(added, ", "))
		bump = "minor"
	}
	return []action{{description: desc, writes: files, bump: bump}}, nil
}
